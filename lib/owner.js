function getOwnerNumbers() {
    return (global.ownerNumbers || [])
        .map((n) => String(n).replace(/[^0-9]/g, ''))
        .filter(Boolean);
}

async function isOwner(zack, jid) {
    if (!jid) return false;

    let numberJid = jid;

    if (jid.endsWith('@lid')) {
        try {
            const pn = await zack.signalRepository.lidMapping.getPNForLID(jid);
            if (pn) numberJid = pn;
        } catch (e) {
            
        }
    }

    const number = numberJid.split('@')[0].split(':')[0];
    return getOwnerNumbers().includes(number);
}

module.exports = { isOwner, getOwnerNumbers };